/*
 * 哪天上学、哪天放假 —— 2026 年
 *
 * 为什么要有这个文件：孩子练多少，和"今天上学还是放假"直接相关。
 * 放假的日子时间多，可以多练一份大的；而**调休补班的周六周日是要上学的**，
 * 那天就别催他多练 —— 光看"今天是不是周末"会算错这一种。
 *
 * 数据来源：国务院办公厅《关于 2026 年部分节假日安排的通知》
 *   国办发明电〔2025〕7 号（2025-11-04 发布，中国政府网）
 *   https://www.gov.cn/zhengce/zhengceku/202511/content_7047091.htm
 * 抄录日期：2026-09-26。
 *
 * **第二年要换表。** 表里没有的年份会自动退回"周末算放假"的规则
 * （见 dayKind），不会算错到让页面出错，只是不认识法定假日了。
 * 换表时照着上面那个链接抄 OFF / WORK 两张表就行，函数一个字都不用动。
 */
(function (root, factory) {
  var mod = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = mod;
  else root.Holidays = mod;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var SOURCE = '国办发明电〔2025〕7 号';

  // 放假的日子（七天长假、三天小长假都算在里面）
  var OFF = {
    '2026-01-01': '元旦', '2026-01-02': '元旦', '2026-01-03': '元旦',
    '2026-02-15': '春节', '2026-02-16': '春节', '2026-02-17': '春节',
    '2026-02-18': '春节', '2026-02-19': '春节', '2026-02-20': '春节',
    '2026-02-21': '春节', '2026-02-22': '春节', '2026-02-23': '春节',
    '2026-04-04': '清明节', '2026-04-05': '清明节', '2026-04-06': '清明节',
    '2026-05-01': '劳动节', '2026-05-02': '劳动节', '2026-05-03': '劳动节',
    '2026-05-04': '劳动节', '2026-05-05': '劳动节',
    '2026-06-19': '端午节', '2026-06-20': '端午节', '2026-06-21': '端午节',
    '2026-09-25': '中秋节', '2026-09-26': '中秋节', '2026-09-27': '中秋节',
    '2026-10-01': '国庆节', '2026-10-02': '国庆节', '2026-10-03': '国庆节',
    '2026-10-04': '国庆节', '2026-10-05': '国庆节', '2026-10-06': '国庆节',
    '2026-10-07': '国庆节'
  };

  // 调休上班的日子：这些**周末是要上学的**
  var WORK = {
    '2026-01-04': '元旦',
    '2026-02-14': '春节', '2026-02-28': '春节',
    '2026-05-09': '劳动节',
    '2026-09-20': '国庆节', '2026-10-10': '国庆节'
  };

  function ymd(ts) {
    var d = new Date(ts);
    var m = d.getMonth() + 1, day = d.getDate();
    return d.getFullYear() + '-' + (m < 10 ? '0' : '') + m + '-' + (day < 10 ? '0' : '') + day;
  }

  // 这一天是什么日子。
  // 返回 { kind: 'school' | 'off', label, holiday }
  //   kind  —— 要上学 / 放假（判难度、判要不要提示"多练一份"，看这一个就够）
  //   label —— 界面能直接用的一句话（空字符串表示"没什么好说的平常日子"）
  //
  // 判定顺序很重要：**补班日排在最前面**。9 月 20 日是周日，但那天要上学；
  // 先看周末就会把它判成放假，孩子会被推着多做一份 —— 正好反了。
  function dayKind(ts) {
    var key = ymd(ts);
    if (WORK[key]) {
      return { kind: 'school', label: WORK[key] + '调休，今天要上学', holiday: WORK[key] };
    }
    if (OFF[key]) {
      return { kind: 'off', label: OFF[key] + '假期', holiday: OFF[key] };
    }
    var wd = new Date(ts).getDay();
    if (wd === 0 || wd === 6) return { kind: 'off', label: '周末', holiday: '' };
    return { kind: 'school', label: '', holiday: '' };
  }

  function isOff(ts) { return dayKind(ts).kind === 'off'; }

  return {
    SOURCE: SOURCE,
    OFF: OFF,
    WORK: WORK,
    ymd: ymd,
    dayKind: dayKind,
    isOff: isOff
  };
});
